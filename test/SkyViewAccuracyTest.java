    private static final Instant J2000 = LocalDateTime.of(2000, 1, 1, 12, 0).toInstant(ZoneOffset.UTC);

    @Test
    void altAzMatchesAstropy() {
        SkyView sv = new SkyView(new SkyView.Host() {
            public double simTimeSec() { return 0; }
            public void repaint() { }
            public java.awt.Component component() { return null; }
            public void goToNow() { }
        });
        double worstStar = 0, worstBody = 0;
        for (String[] r : REF) {
            sv.setLocation(r[0], Double.parseDouble(r[1]), Double.parseDouble(r[2]), false);
            double t = Duration.between(J2000, Instant.parse(r[3])).toMillis() / 1000.0;
            boolean star = r[4].startsWith("HR");
            double[] got = star ? sv.starAltAzDeg(Integer.parseInt(r[4].substring(2)), t) : sv.altAzDeg(r[4], t);
            double alt = Double.parseDouble(r[5]), az = Double.parseDouble(r[6]);
            // Great-circle separation between the two apparent positions.
            double a1 = Math.toRadians(got[0]), a2 = Math.toRadians(alt), dz = Math.toRadians(got[1] - az);
            double sep = Math.toDegrees(Math.acos(Math.min(1, Math.sin(a1) * Math.sin(a2) + Math.cos(a1) * Math.cos(a2) * Math.cos(dz))));
            if (star) worstStar = Math.max(worstStar, sep); else worstBody = Math.max(worstBody, sep);
            assertTrue(sep < (star ? 0.02 : 0.03), r[4] + " from " + r[0] + " at " + r[3] + " off by " + sep + " deg");
        }
        System.out.printf("  worst star %.4f deg, worst Sun/Moon/planet %.4f deg over %d positions%n", worstStar, worstBody, REF.length);
    }

    @Test
    void typedDatesAreReadInTheirTimeZone() {
        ZoneId toronto = ZoneId.of("America/Toronto");
        // Midnight local in Toronto (EDT, UTC-4) is 04:00 UTC — not 00:00 UTC.
        assertEquals(LocalDateTime.of(2026, 10, 3, 4, 1), SolarSystemSimulation.parseDateTimeInZone("2026-10-03 00:01", toronto));
        assertEquals(LocalDateTime.of(2026, 10, 3, 0, 1), SolarSystemSimulation.parseDateTimeInZone("2026-10-03 00:01 UTC", toronto));
        assertEquals(LocalDateTime.of(2026, 10, 2, 15, 1), SolarSystemSimulation.parseDateTimeInZone("2026-10-03 00:01 +09:00", toronto));
        assertEquals(LocalDateTime.of(2026, 10, 2, 15, 1), SolarSystemSimulation.parseDateTimeInZone("2026-10-03 00:01 Asia/Tokyo", toronto));
        assertEquals(LocalDateTime.of(2026, 10, 3, 4, 1), SolarSystemSimulation.parseDateTimeInZone("2026-10-03 00:01 EDT", toronto));
        // Winter: EST, UTC-5.
        assertEquals(LocalDateTime.of(2026, 1, 15, 5, 0), SolarSystemSimulation.parseDateTimeInZone("2026-01-15", toronto));
    }
