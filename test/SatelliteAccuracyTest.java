    @Test
    void moonsMatchHorizons() {
        double worst = 0;
        for (double[] r : REF) {
            int p = (int) r[0], m = (int) r[1];
            double[] got = SatelliteEphemeris.positionKm(p, m, (r[2] - 2451545.0) * 86_400.0);
            double[] ref = {r[3] * AU_KM, r[4] * AU_KM, r[5] * AU_KM};
            double sepDeg = AccuracyTest.sepArcsec(got, ref) / 3600.0;
            double rg = Math.sqrt(got[0]*got[0] + got[1]*got[1] + got[2]*got[2]);
            double rr = Math.sqrt(ref[0]*ref[0] + ref[1]*ref[1] + ref[2]*ref[2]);
            String name = SolarSystemSimulation.MOON_NAMES[p][m];
            System.out.printf("  %s JD %.1f: %.3f deg, distance %+.3f%%%n", name, r[2], sepDeg, 100 * (rg / rr - 1));
            worst = Math.max(worst, sepDeg);
            assertTrue(sepDeg < 0.15, name + " off by " + sepDeg + " deg at JD " + r[2]);
            assertEquals(1.0, rg / rr, 0.005, name + " distance");
        }
        System.out.printf("  worst moon error: %.3f deg%n", worst);
    }

    @Test
    void tableOrderMatchesSimMoonNames() {
        // The satellite rows must line up with the sim's moon lists (Earth's Moon is separate).
        for (int p = 0; p < SolarSystemSimulation.MOON_NAMES.length; p++) {
            int expected = (p == 2) ? 0 : SolarSystemSimulation.MOON_NAMES[p].length;
            assertEquals(expected, SatelliteEphemeris.count(p), "moon count for planet " + p);
        }
        // Periods implied by the fitted mean motions agree with the tabulated sidereal periods.
        for (int p = 3; p <= 8; p++)
            for (int m = 0; m < SatelliteEphemeris.count(p); m++)
                assertEquals(SolarSystemSimulation.MOON_PERIOD_DAYS[p][m], SatelliteEphemeris.periodDays(p, m),
                        0.002 * SolarSystemSimulation.MOON_PERIOD_DAYS[p][m], SolarSystemSimulation.MOON_NAMES[p][m]);
    }

    @Test
    void plutoAndCharonOrbitTheirBarycentre() {
        // Pluto's centre sits ~2100 km from the Pluto-Charon barycentre, on the far side from Charon.
        double[] off = SatelliteEphemeris.centreOffsetKm(8, 0);
        double[] ch = SatelliteEphemeris.positionKm(8, 0, 0);
        double d = Math.sqrt(off[0]*off[0] + off[1]*off[1] + off[2]*off[2]);
        assertEquals(2130, d, 60, "Pluto's offset from the barycentre (km)");
        double dot = off[0]*ch[0] + off[1]*ch[1] + off[2]*ch[2];
        assertTrue(dot < 0, "Pluto must be displaced away from Charon");
    }
